#!/usr/bin/env python3
"""Writes rust/crates/companion/src/tables_gen.rs from 3ds/core/pd_tables_gen.c.

That C file is itself generated from the app's Kotlin tables (3ds/tools/gen_tables.py), so the Rust tables
follow the app's through it: regenerate the C first (`make -C 3ds tables`), then run this.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "3ds/core/pd_tables_gen.c"
OUT = REPO / "rust/crates/companion/src/tables_gen.rs"

C_STRING = r'"(?:[^"\\]|\\.)*"'


def arrays(text):
    """name -> body, for every `const ... name[N]... = { body };`."""
    out = {}
    for m in re.finditer(r"const [^=;]*?\b(\w+)\[\d+\](?:\[\d+\])?\s*=\s*\{(.*?)\n\};", text, re.S):
        out[m.group(1)] = m.group(2)
    return out


def rust_str(c_literal):
    # C and Rust escapes agree for what these tables hold (\" and \\); keep the UTF-8 as is.
    return c_literal


def strings(body):
    items = re.findall(r"NULL|" + C_STRING, body)
    return [None if s == "NULL" else s for s in items]


def tuples(body):
    return re.findall(r"\{\s*([^{}]*?)\s*\}", body)


def main():
    text = SRC.read_text(encoding="utf-8")
    a = arrays(text)
    lines = [
        "// Generated by rust/tools/gen_tables.py from 3ds/core/pd_tables_gen.c (itself from the app's Kotlin",
        "// tables) - do not hand-edit.",
        "#![allow(clippy::all)]",
        "",
    ]

    def str_table(rust_name, c_name):
        items = strings(a[c_name])
        lines.append(f"pub static {rust_name}: [Option<&str>; {len(items)}] = [")
        for s in items:
            lines.append("    None," if s is None else f"    Some({rust_str(s)}),")
        lines.append("];")
        lines.append("")

    str_table("SPECIES_NAMES", "pd_species_names")
    str_table("TYPE_NAMES", "pd_type_names")
    str_table("MAPSEC_FIRERED", "pd_mapsec_firered")
    str_table("MAPSEC_EMERALD", "pd_mapsec_emerald")
    str_table("ITEM_NAMES_FIRERED", "pd_item_names_firered")
    str_table("ITEM_DESC_FIRERED", "pd_item_desc_firered")
    str_table("ITEM_NAMES_EMERALD", "pd_item_names_emerald")
    str_table("ITEM_DESC_EMERALD", "pd_item_desc_emerald")

    moves = tuples(a["pd_moves"])
    lines.append(f"/// (name, type, power) by move id.")
    lines.append(f"pub static MOVES: [(Option<&str>, u8, u16); {len(moves)}] = [")
    for t in moves:
        m = re.match(r"(NULL|" + C_STRING + r")\s*,\s*(\d+)\s*,\s*(\d+)", t)
        name = "None" if m.group(1) == "NULL" else f"Some({rust_str(m.group(1))})"
        lines.append(f"    ({name}, {m.group(2)}, {m.group(3)}),")
    lines.append("];")
    lines.append("")

    chart = tuples(a["pd_type_chart"])
    lines.append("/// (attacking type, defending type, percent): the pairs that aren't 100%.")
    lines.append(f"pub static TYPE_CHART: [(u8, u8, u16); {len(chart)}] = [")
    for t in chart:
        x, y, z = [v.strip() for v in t.split(",")]
        lines.append(f"    ({x}, {y}, {z}),")
    lines.append("];")
    lines.append("")

    ratios = [v.strip() for v in a["pd_gender_ratios"].replace("\n", " ").split(",") if v.strip()]
    lines.append("/// gBaseStats[species].genderRatio (FireRed's numbering, which Emerald shares).")
    lines.append(f"pub static GENDER_RATIOS: [u8; {len(ratios)}] = [{', '.join(ratios)}];")
    lines.append("")

    types = tuples(a["pd_species_type_table"])
    lines.append("/// A species' two types (the same twice for one type; 255 = unknown).")
    lines.append(f"pub static SPECIES_TYPES: [(u8, u8); {len(types)}] = [")
    for t in types:
        x, y = [v.strip() for v in t.split(",")]
        lines.append(f"    ({x}, {y}),")
    lines.append("];")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}", file=sys.stderr)


if __name__ == "__main__":
    main()
